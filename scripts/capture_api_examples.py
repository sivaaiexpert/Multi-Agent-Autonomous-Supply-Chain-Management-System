"""Generate docs/openapi.json and docs/product/API_EXAMPLES.md from REAL calls against the real app (synthetic tenant, in-process).

    python -m scripts.capture_api_examples

Nothing in the examples is hand-written: each request is executed and its actual response (truncated for length, API keys masked) is written down.
"""
from __future__ import annotations

import base64
import json
import os
import shutil
import sys
import tempfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))


def main() -> int:
    tmp = Path(tempfile.mkdtemp(prefix="scm_api_ex_"))
    os.environ.update({"SCM_DATA_DIR": str(tmp / "data"), "SCM_CONTROL_DB": str(tmp / "data" / "control.db"), "SCM_ENV": "development", "SCM_ALLOW_PRIVATE_URLS": "1",
                       "SCM_OBS__LOG_LEVEL": "ERROR", "SCM_RATE_LIMIT_PER_MIN": "100000"})
    from enterprise import controlplane, profiles, secrets_store, tenancy
    os.environ["SCM_SECRET_KEY"] = secrets_store.generate_secret_key()
    from scm import db, security
    from scm.security import Role
    db.DB_PATH, db.OUTBOX = tmp / "default.db", tmp / "default_outbox"
    controlplane.reset()
    from fastapi.testclient import TestClient

    from api.main import create_app
    tenancy.provision("acme-demo", "Acme Demo (synthetic)", "professional", "SANDBOX", is_demo=True)
    with tenancy.scope("acme-demo"):
        profiles.load_into_current_tenant(profiles.generate("retailer", 7, 0.06))
    cp = controlplane.get()
    keys = {}
    for role in (Role.TENANT_ADMIN, Role.OPERATOR, Role.APPROVER, Role.VIEWER):
        uid = role.value.lower().replace("_", "-")
        cp.create_user("acme-demo", uid, f"{uid}@acme.example", uid, role)
        keys[role] = cp.issue_key("acme-demo", uid, "docs")[0]
    root_key, entry = security.generate_key(Role.SUPER_ADMIN, "platform-root")
    secrets_to_mask = [*keys.values(), root_key]

    def H(role):
        return {"X-API-Key": keys[role]}
    out: list[str] = ["# API examples (captured from real calls)", "",
                      "Generated by `python -m scripts.capture_api_examples` against a SYNTHETIC demo tenant (`acme-demo`) with the in-process app. Each response below is the actual output of the "
                      "request above it (long bodies truncated with `...`; API keys masked as `scm_...`). Identifiers and timestamps differ per run.", "",
                      "Base path `/api/v1`. Authenticate with `X-API-Key: <key>` or `Authorization: Bearer <key>`. Errors are always `{\"error\": {\"code\", \"message\", \"request_id\"}}`.", ""]

    def mask(text: str) -> str:
        for k in secrets_to_mask:
            text = text.replace(k, "scm_...")
        return text

    def show(c, title: str, method: str, path: str, role=None, body: dict | None = None, headers: dict | None = None, content: bytes | None = None, limit: int = 1100):
        h = {**(H(role) if role else {}), **(headers or {})}
        r = c.request(method, path, headers=h, json=body if content is None else None, content=content)
        shown_h = {k: ("scm_..." if k.lower() == "x-api-key" else v) for k, v in h.items() if k.lower() != "content-type"}
        req = f"{method} /api/v1{path[len('/api/v1'):] if path.startswith('/api/v1') else path}" if not path.startswith("/api/v1") else f"{method} {path}"
        txt = r.text
        try:
            txt = json.dumps(r.json(), indent=2)
        except ValueError:
            pass
        txt = mask(txt)
        if len(txt) > limit:
            txt = txt[:limit] + "\n  ..."
        out.extend([f"## {title}", "", "```http", req, *(f"{k}: {v}" for k, v in shown_h.items())] + ([""] + [json.dumps(body, indent=2)] if body else []) + ["```", "", f"Response **{r.status_code}**", "", "```json", txt, "```", ""])
        return r

    with TestClient(create_app(keyring=security.load_keyring(entry)), raise_server_exceptions=False) as c:
        show(c, "Liveness / readiness (no key)", "GET", "/ready")
        show(c, "Missing key", "GET", "/api/v1/inventory")
        show(c, "Inventory (paged)", "GET", "/api/v1/inventory?limit=2", Role.VIEWER)
        show(c, "Stock-out risk (deterministic engine)", "GET", "/api/v1/risks?limit=2", Role.VIEWER)
        show(c, "Forecasts", "GET", "/api/v1/forecasts?limit=1", Role.VIEWER)
        show(c, "Viewer cannot start a workflow (RBAC)", "POST", "/api/v1/workflows", Role.VIEWER)
        r = show(c, "Start a procurement workflow", "POST", "/api/v1/workflows", Role.OPERATOR, headers={"Idempotency-Key": "docs-example-1"})
        wf = r.json().get("workflow_id")
        for _ in range(120):
            g = c.get(f"/api/v1/workflows/{wf}", headers=H(Role.VIEWER)).json()
            if g["status"] != "RUNNING" and g["status"] != "PENDING":
                break
            time.sleep(0.25)
        show(c, "Workflow waiting at the human gate", "GET", f"/api/v1/workflows/{wf}", Role.VIEWER, limit=1800)
        show(c, "Approvals inbox (approver)", "GET", "/api/v1/approvals", Role.APPROVER, limit=500)
        show(c, "Approve", "POST", f"/api/v1/workflows/{wf}/approve", Role.APPROVER, body={"reason": "reviewed"})
        for _ in range(120):
            if c.get(f"/api/v1/workflows/{wf}", headers=H(Role.VIEWER)).json()["status"] not in ("RUNNING", "AWAITING_APPROVAL"):
                break
            time.sleep(0.25)
        show(c, "Explanation generated from stored data", "GET", f"/api/v1/workflows/{wf}/explanation", Role.VIEWER, limit=1500)
        show(c, "Decision trace (full chain; needs the view_trace permission, which VIEWER lacks)", "GET", f"/api/v1/workflows/{wf}/trace", Role.TENANT_ADMIN, limit=900)
        show(c, "What-if: demand +30%", "POST", "/api/v1/simulations/what-if", Role.TENANT_ADMIN, body={"name": "demand +30%", "demand_multiplier": 1.3}, limit=900)
        show(c, "Baseline vs optimised decision", "GET", "/api/v1/procurement/comparison", Role.TENANT_ADMIN, limit=900)
        csv = "sku,name,reorder_point,target_stock\nNEW-1,Example item,10,80\nNEW-2,Another item,5,x\n"
        pv = show(c, "Import preview (with column mapping; one bad row)", "POST", "/api/v1/imports/preview", Role.TENANT_ADMIN, limit=1500,
                  body={"entity": "products", "filename": "products.csv", "content_base64": base64.b64encode(csv.encode()).decode(),
                        "mapping": {"columns": {"sku": "sku_id", "name": "name", "reorder_point": "reorder_point", "target_stock": "target_stock"}}})
        job = pv.json().get("job_id")
        if job:
            show(c, "Commit a previewed import", "POST", f"/api/v1/imports/{job}/commit", Role.TENANT_ADMIN, limit=700)
        ig = show(c, "Create an inbound-webhook integration (secret shown once)", "POST", "/api/v1/integrations", Role.TENANT_ADMIN, body={"kind": "webhook_in", "name": "ERP events", "config": {"source": "erp"}})
        secret = ig.json().get("secret_shown_once")
        if secret:
            with tenancy.scope("acme-demo"):
                sku = db.df("SELECT Item_ID FROM inventory ORDER BY Item_ID LIMIT 1").Item_ID[0]
            body = json.dumps({"id": "evt-1001", "type": "inventory.updated", "data": {"sku_id": sku, "quantity": 120}}).encode()
            sig, _ = security.sign_payload(secret, body)
            hd = {"X-SCM-Signature": sig.replace(sig.split("v1=")[1], "<hmac>"), "X-SCM-Event-ID": "evt-1001", "X-SCM-Event-Type": "inventory.updated"}
            real = {"X-SCM-Signature": sig, "X-SCM-Event-ID": "evt-1001", "X-SCM-Event-Type": "inventory.updated", "Content-Type": "application/json"}
            r1 = c.post("/api/v1/webhooks/inbound/acme-demo/erp", content=body, headers=real)
            r2 = c.post("/api/v1/webhooks/inbound/acme-demo/erp", content=body, headers=real)
            r3 = c.post("/api/v1/webhooks/inbound/acme-demo/erp", content=body, headers={**real, "X-SCM-Signature": "t=1,v1=" + "0" * 64})
            out.extend(["## Signed inbound webhook (first delivery, duplicate, forged)", "", "```http", "POST /api/v1/webhooks/inbound/acme-demo/erp", *(f"{k}: {v}" for k, v in hd.items()), "", body.decode(), "```", "",
                        f"First delivery -> **{r1.status_code}** `{r1.text}`  ", f"Same event again -> **{r2.status_code}** `{r2.text}`  ", f"Bad signature -> **{r3.status_code}** `{mask(r3.text)}`", ""])
        show(c, "Usage (billing-ready metering, no prices)", "GET", "/api/v1/usage", Role.TENANT_ADMIN, limit=1200)
        show(c, "Business dashboard", "GET", "/api/v1/dashboards/business", Role.VIEWER, limit=800)
        show(c, "Report as JSON", "GET", "/api/v1/reports/inventory_risk?format=json", Role.TENANT_ADMIN, limit=800)
        show(c, "Validation error", "POST", "/api/v1/simulations/what-if", Role.TENANT_ADMIN, body={"demand_multiplier": -5})
        show(c, "Tenant admin cannot manage tenants (RBAC)", "GET", "/api/v1/admin/tenants", Role.TENANT_ADMIN)
        root_h = {"X-API-Key": root_key}
        r = c.get("/api/v1/admin/tenants", headers=root_h)
        out.extend(["## Platform operator lists tenants (SUPER_ADMIN)", "", "```http", "GET /api/v1/admin/tenants", "X-API-Key: scm_...", "```", "", f"Response **{r.status_code}**", "", "```json", mask(json.dumps(r.json(), indent=2))[:900], "```", ""])
        spec = c.get("/openapi.json").json()
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "product").mkdir(exist_ok=True)
    (ROOT / "docs" / "openapi.json").write_text(json.dumps(spec, indent=2), encoding="utf-8")
    (ROOT / "docs" / "product" / "API_EXAMPLES.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    paths = sorted(spec["paths"])
    print(f"wrote docs/openapi.json ({len(paths)} paths) and docs/product/API_EXAMPLES.md")
    controlplane.reset()
    shutil.rmtree(tmp, ignore_errors=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
